// 接缝 forwarder-script 模块行为测试(契约 T2「测试规格」表 5-7 行 + 命令串引号约定)
// 期望值来源:spec「应用外裸跑零发送」「fail-open 纪律」「事件名走命令参数」;引号规则与
// quoteLaunchArg 同约定(含空白才包裹,Windows 路径不含 ",不涉转义矩阵)。
import { describe, expect, it } from 'vitest'
import {
  FORWARDER_SCRIPT_BASENAME,
  HOOK_LAUNCHER_BASENAME,
  buildHookCommand,
  generateForwarderScript,
  generateHookLauncherCmd
} from './forwarder-script'

const SCRIPT = generateForwarderScript()

describe('generateForwarderScript(文本断言)', () => {
  it('5. 三个 env 任一缺失即 exit(0)(应用外裸跑零发送)', () => {
    const guard = SCRIPT.match(
      /if \(!port \|\| !sessionId \|\| !token\) process\.exit\(0\)/
    )
    expect(guard, '缺 env 早退分支必须存在').toBeTruthy()
  })

  it('6. fetch 失败静默且最终恒 exit(0)(fail-open)', () => {
    expect(SCRIPT).toContain('.catch(() => {})')
    expect(SCRIPT).toContain('finally(() => process.exit(0))')
    expect(SCRIPT).toContain("setTimeout(() => process.exit(0), 3000)")
  })

  it('7. --agent / --event 命令行参数解析并进 body', () => {
    expect(SCRIPT).toContain("argOf('--agent')")
    expect(SCRIPT).toContain("argOf('--event')")
    expect(SCRIPT).toContain('JSON.stringify({ agent, sessionId, event, payload:')
  })

  it('脚本头部带 managed 标注(防用户误编辑;认领锚点为文件名)', () => {
    expect(SCRIPT).toContain('Generated by Soloport')
    expect(SCRIPT).toContain('do not edit')
  })
})

describe('buildHookCommand(实机实证形态:裸路径/正斜杠/无引号)', () => {
  const LAUNCHER = 'C:\\Users\\oberg\\AppData\\Roaming\\Soloport\\hook-scripts\\soloport-hook.cmd'

  it('命令串 = launcher 裸路径(正斜杠无引号)+ 裸参数', () => {
    expect(buildHookCommand(LAUNCHER, 'claude', 'Stop')).toBe(
      'C:/Users/oberg/AppData/Roaming/Soloport/hook-scripts/soloport-hook.cmd --agent claude --event Stop'
    )
  })

  it('认领锚点常量 = 脚本文件名稳定子串', () => {
    expect(FORWARDER_SCRIPT_BASENAME).toBe('forwarder.mjs')
    expect(HOOK_LAUNCHER_BASENAME).toBe('soloport-hook.cmd')
    expect(LAUNCHER).toContain(HOOK_LAUNCHER_BASENAME)
  })
})

describe('generateHookLauncherCmd(内部引号承载带空格 node 路径)', () => {
  it('launcher 内容 = 带引号 node + 带引号 forwarder + %*,CRLF 行尾', () => {
    const content = '@echo off\r\n"C:\\Program Files\\nodejs\\node.exe" "C:\\solo\\forwarder.mjs" %*\r\n'
    expect(generateHookLauncherCmd('C:\\Program Files\\nodejs\\node.exe', 'C:\\solo\\forwarder.mjs')).toBe(content)
  })
})
