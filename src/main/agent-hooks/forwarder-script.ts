// hook 转发脚本(hook-run-state T2):生成 agent hook 配置指向的共享转发脚本。
// 事件名与 agentId 走命令行参数(--agent/--event),脚本不解析各家 payload 字段差异;
// stdin 载荷原样转交(主进程接收器归一化)。fail-open 纪律:任何失败静默,恒 exit 0——
// 转发失败绝不能影响 agent 会话本身。
// 应用外裸跑的会话没有 PTY 注入的 env 令牌 → 脚本早退零发送(spec「影响应用外会话从根上不存在」)。
import { mkdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

// 认领键的稳定子串(hook-run-state 评审定案:配置合并按「command 含本脚本文件名」认领,
// 不用完整路径——防安装位置/userData 路径漂移导致旧条目失认成重复注入)
export const FORWARDER_SCRIPT_BASENAME = 'forwarder.mjs'
// Windows 托管 launcher(实证形态见 buildHookCommand):内部引号原生安全,承载带空格的 node 路径
export const HOOK_LAUNCHER_BASENAME = 'soloport-hook.cmd'

// 转发脚本内容。要点(均有测试文本断言钉住):
// ① 三个 env 令牌任一缺失即 exit(0)——应用外会话零发送;② fetch 失败静默且恒 exit(0);
// ③ --agent/--event 命令行参数进 body;④ stdin 载荷原样转交不解析;⑤ 2s 超时护栏 +
// 3s 无 stdin 兜底(bounded:hook 不得拖住 agent 会话)。
export function generateForwarderScript(): string {
  return `// Generated by Soloport (managed hook forwarder) — do not edit; reconciled on app start.
// Forwards one agent hook event to the Soloport receiver over loopback HTTP.
// Env tokens are injected into the PTY by Soloport at spawn; without them (agent run
// outside Soloport) this exits silently — hand-run sessions are never touched.
// Fail-open: every failure is silent and the process always exits 0.

const port = process.env.SOLOPORT_HOOK_PORT
const sessionId = process.env.SOLOPORT_SESSION_ID
const token = process.env.SOLOPORT_HOOK_TOKEN
if (!port || !sessionId || !token) process.exit(0)

const args = process.argv.slice(2)
function argOf(name) {
  const i = args.indexOf(name)
  return i >= 0 ? args[i + 1] : undefined
}
const agent = argOf('--agent')
const event = argOf('--event')
if (!agent || !event) process.exit(0)

const chunks = []
process.stdin.on('data', (chunk) => chunks.push(chunk))
process.stdin.on('end', () => {
  const body = JSON.stringify({ agent, sessionId, event, payload: Buffer.concat(chunks).toString('utf8') })
  fetch('http://127.0.0.1:' + port + '/hook', {
    method: 'POST',
    headers: { 'content-type': 'application/json', 'x-soloport-token': token },
    body,
    signal: AbortSignal.timeout(2000)
  })
    .catch(() => {})
    .finally(() => process.exit(0))
})
// stdin 兜底:个别宿主下 end 可能不来,3s 后放行(不拖住 agent 会话)
setTimeout(() => process.exit(0), 3000).unref()
`
}

// Windows 托管 launcher 内容(cmd 批处理):内部引号原生安全,承载带空格的 node/脚本绝对路径;
// %* 透传 --agent/--event。CRLF(批处理按行解析,与行尾无关,但统一 CRLF 防意外)。
// 2026-11-23 实机探针(claude 2.1.220):hook 命令串的可用形态 = 裸路径 + 正斜杠 + 无引号 +
// 无空格,指向此 launcher;node 的引号在 launcher 文件内原样生效(探针 full-chain PASS)。
export function generateHookLauncherCmd(nodePath: string, forwarderPath: string): string {
  return '@echo off\r\n"' + nodePath + '" "' + forwarderPath + '" %*\r\n'
}

// hook 配置里的命令串:指向 launcher 的裸路径(正斜杠、无引号、无空格——userData 路径受控,
// 注入器 reconcile 时校验不含空白)+ 参数。任何带空格/引号的形态在 claude 2.1.220 实测不触发。
export function buildHookCommand(launcherPath: string, agent: string, event: string): string {
  return `${launcherPath.replace(/\\/g, '/')} --agent ${agent} --event ${event}`
}

// 脚本落盘(userData/hook-scripts/):存在即覆盖(内容随应用版本刷新);返回脚本绝对路径。
// 目录不存在则创建(best-effort:失败抛给调用方,编排层决定降级)。
export async function writeForwarderScript(dir: string, content?: string): Promise<string> {
  await mkdir(dir, { recursive: true })
  const scriptPath = join(dir, FORWARDER_SCRIPT_BASENAME)
  await writeFile(scriptPath, content ?? generateForwarderScript(), 'utf8')
  return scriptPath
}
